// Writes src/data/deutschSeriesOverrides.ts: the series label from each part's Technical Specifications
// (deutsch-attributes.json "Series") for the families where the series code in deutsch-products.json is
// wrong. AMPSEAL parts are stored there as "DT" (259 parts), so their titles read "DT Series".
// Add a pattern to FAMILIES to correct another family. Run: node scripts/catalogue/generate-deutsch-series-overrides.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const FAMILIES = [/^AMPSEAL\b/i];

const root = process.cwd();
const attrs = JSON.parse(readFileSync(join(root, "src/data/generated/deutsch-attributes.json"), "utf8"));
const entries = Object.entries(attrs.products)
  .filter(([, a]) => a.Series && FAMILIES.some((re) => re.test(a.Series)))
  .map(([pn, a]) => `  ${JSON.stringify(pn.toUpperCase())}: ${JSON.stringify(a.Series)},`);

const file = `// Generated by scripts/catalogue/generate-deutsch-series-overrides.mjs, do not edit by hand.
// Parts whose Technical Specifications "Series" belongs to another family than the series code in
// deutsch-products.json (AMPSEAL parts are stored there as "DT"). Keyed by upper-case part number.
export const DEUTSCH_SERIES_OVERRIDES: Record<string, string> = {
${entries.join("\n")}
};
`;
writeFileSync(join(root, "src/data/deutschSeriesOverrides.ts"), file);
console.log(`wrote ${entries.length} overrides`);
